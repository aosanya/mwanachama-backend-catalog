// Command ddl prints the DDL a spec would run, without touching a database.
//
// It exists so a spec can be reviewed as SQL before it is trusted, and so a
// deployment that applies schema changes through its own migration tooling
// — `supabase db push`, say — can take the statements from the spec rather
// than write them again by hand.
//
//	ddl <spec.json> [postgres|sqlite]
//
// The output is what spec.Migrate executes, in the same order.
package main

import (
	"fmt"
	"os"

	"github.com/aosanya/mwanachama-backend-catalog/spec"
)

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: ddl <spec.json> [postgres|sqlite]")
		os.Exit(2)
	}
	dialect := "postgres"
	if len(os.Args) > 2 {
		dialect = os.Args[2]
	}

	s, err := spec.Load(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	fmt.Printf("-- generated by cmd/ddl from %s\n", os.Args[1])
	fmt.Printf("-- module %s, domain %s, instance %s — do not edit by hand\n\n",
		s.Module, s.Domain, s.Instance)
	for _, stmt := range s.DDL(dialect) {
		fmt.Println(stmt + ";")
	}
}
