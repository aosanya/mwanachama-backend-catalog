// Command seed turns a directory of document folders into SQL, against the
// tables a spec declares.
//
// It exists for a deployment whose schema is applied by its own migration
// tooling — `supabase db push` — and which therefore has no direct database
// connection for cmd/import to use. The statements are written from the
// spec's own table and column names, so a domain that renames its objects
// gets the renamed SQL for free.
//
//	seed -dir <folders> -spec <spec.json> -out <dir> [-chunk 50]
//
// Each folder is one document: agency.json is the document itself, and
// README.md, sales.md and any other *.json beside it are the private parts.
// Re-running is safe — every statement upserts on the slug.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"

	"github.com/google/uuid"

	catalog "github.com/aosanya/mwanachama-backend-catalog"
)

// idNamespace makes a document's id a function of its slug, so seeding
// twice writes the same rows rather than a second copy.
var idNamespace = uuid.NewSHA1(uuid.NameSpaceURL, []byte("mwanachama-backend-catalog/seed"))

var notSlug = regexp.MustCompile(`[^a-z0-9]+`)

// slugPattern is the shape of a document's slug — a data value, which may
// begin with a digit ("1031-exchange-qualified-intermediary"). It is
// deliberately not spec.NamePattern: that governs SQL identifiers, which
// must begin with a letter, and reusing it here silently drops documents.
var slugPattern = regexp.MustCompile(`^[a-z0-9]+(-[a-z0-9]+)*$`)

type doc struct {
	slug          string
	name          string
	summary       string
	document      string
	readme        string
	sales         string
	moduleConfigs string
}

func main() {
	dir := flag.String("dir", "", "directory of document folders (required)")
	specPath := flag.String("spec", "", "the spec whose tables to write (required)")
	out := flag.String("out", "", "directory to write .sql files into (required)")
	chunk := flag.Int("chunk", 50, "documents per file")
	flag.Parse()

	if *dir == "" || *specPath == "" || *out == "" {
		fmt.Fprintln(os.Stderr, "usage: seed -dir <folders> -spec <spec.json> -out <dir> [-chunk 50]")
		os.Exit(2)
	}

	s, err := catalog.LoadSpec(*specPath)
	if err != nil {
		fail("%v", err)
	}
	entry, ok := s.ByRole("entry")
	if !ok {
		fail("spec %s fills no object for the entry role", *specPath)
	}
	private, hasPrivate := s.ByRole("entry_private")

	docs, skipped := readAll(*dir)
	for _, sk := range skipped {
		fmt.Fprintln(os.Stderr, "skipped:", sk)
	}
	if len(docs) == 0 {
		fail("no documents read from %s", *dir)
	}

	if err := os.MkdirAll(*out, 0o755); err != nil {
		fail("out: %v", err)
	}

	now := time.Now().UTC().Format(time.RFC3339)
	// Supabase orders migrations by a 14-digit timestamp prefix, so each
	// chunk takes the next second rather than a suffix on one stamp.
	base := time.Now().UTC()
	files := 0
	for start := 0; start < len(docs); start += *chunk {
		end := min(start+*chunk, len(docs))

		var b strings.Builder
		fmt.Fprintf(&b, "-- generated by cmd/seed from %s\n", *dir)
		fmt.Fprintf(&b, "-- spec %s, documents %d-%d of %d — do not edit by hand\n\n",
			*specPath, start+1, end, len(docs))

		for _, d := range docs[start:end] {
			b.WriteString(entryInsert(s.TableFor(entry), d, now))
			if hasPrivate {
				b.WriteString(privateInsert(s.TableFor(private), d, now))
			}
		}

		stamp := base.Add(time.Duration(files) * time.Second).Format("20060102150405")
		name := filepath.Join(*out, fmt.Sprintf("%s_seed_%s_%03d.sql", stamp, s.Domain, files))
		if err := os.WriteFile(name, []byte(b.String()), 0o644); err != nil {
			fail("write %s: %v", name, err)
		}
		files++
	}

	fmt.Printf("wrote %d documents into %d file(s) under %s (%d skipped)\n",
		len(docs), files, *out, len(skipped))
}

// entryInsert upserts one document. The slug is the natural key, so a
// re-seed updates rather than duplicates; created_at is left alone on a
// conflict because the row's first sighting does not change.
func entryInsert(table string, d doc, now string) string {
	id := uuid.NewSHA1(idNamespace, []byte(d.slug)).String()
	return fmt.Sprintf(
		"insert into %s (id, slug, name, summary, doc, visibility, submitted_by, created_at, updated_at, deleted)\n"+
			"values (%s, %s, %s, %s, %s, 'pending', 'seed', %s, %s, false)\n"+
			"on conflict (slug) do update set\n"+
			"  name = excluded.name, summary = excluded.summary, doc = excluded.doc,\n"+
			"  updated_at = excluded.updated_at;\n\n",
		table, q(id), q(d.slug), q(d.name), q(d.summary), q(d.document), q(now), q(now))
}

func privateInsert(table string, d doc, now string) string {
	configs := "null"
	if d.moduleConfigs != "" {
		configs = q(d.moduleConfigs)
	}
	return fmt.Sprintf(
		"insert into %s (slug, readme, sales, module_configs, updated_at)\n"+
			"values (%s, %s, %s, %s, %s)\n"+
			"on conflict (slug) do update set\n"+
			"  readme = excluded.readme, sales = excluded.sales,\n"+
			"  module_configs = excluded.module_configs, updated_at = excluded.updated_at;\n\n",
		table, q(d.slug), q(d.readme), q(d.sales), configs, q(now))
}

// q quotes a value as a SQL string literal. Everything written here is
// data — a document, a readme — so doubling the quote is the whole escape.
func q(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

func readAll(dir string) ([]doc, []string) {
	names, err := os.ReadDir(dir)
	if err != nil {
		fail("read %s: %v", dir, err)
	}
	sort.Slice(names, func(i, j int) bool { return names[i].Name() < names[j].Name() })

	var out []doc
	var skipped []string
	for _, n := range names {
		if !n.IsDir() {
			continue
		}
		d, err := readFolder(dir, n.Name())
		if err != nil {
			skipped = append(skipped, fmt.Sprintf("%s: %v", n.Name(), err))
			continue
		}
		out = append(out, d)
	}
	return out, skipped
}

func readFolder(dir, name string) (doc, error) {
	path := filepath.Join(dir, name)
	raw, err := os.ReadFile(filepath.Join(path, "agency.json"))
	if err != nil {
		return doc{}, fmt.Errorf("no agency.json")
	}
	if !json.Valid(raw) {
		return doc{}, fmt.Errorf("agency.json does not parse")
	}

	var head struct {
		Agency struct {
			Name        string `json:"name"`
			Description string `json:"description"`
		} `json:"agency"`
	}
	if err := json.Unmarshal(raw, &head); err != nil {
		return doc{}, err
	}
	if head.Agency.Name == "" {
		return doc{}, fmt.Errorf("no agency.name")
	}

	slug := strings.Trim(notSlug.ReplaceAllString(strings.ToLower(name), "-"), "-")
	if !slugPattern.MatchString(slug) {
		return doc{}, fmt.Errorf("folder name yields no usable slug")
	}

	configs, err := readConfigs(path)
	if err != nil {
		return doc{}, err
	}
	return doc{
		slug:          slug,
		name:          head.Agency.Name,
		summary:       head.Agency.Description,
		document:      string(raw),
		readme:        readFile(filepath.Join(path, "README.md")),
		sales:         readFile(filepath.Join(path, "sales.md")),
		moduleConfigs: configs,
	}, nil
}

func readConfigs(path string) (string, error) {
	names, err := os.ReadDir(path)
	if err != nil {
		return "", err
	}
	configs := map[string]json.RawMessage{}
	for _, n := range names {
		fn := n.Name()
		if n.IsDir() || fn == "agency.json" || !strings.HasSuffix(fn, ".json") {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(path, fn))
		if err != nil {
			return "", err
		}
		if !json.Valid(raw) {
			return "", fmt.Errorf("%s does not parse", fn)
		}
		configs[strings.TrimSuffix(fn, ".json")] = raw
	}
	if len(configs) == 0 {
		return "", nil
	}
	b, err := json.Marshal(configs)
	if err != nil {
		return "", err
	}
	return string(b), nil
}

func readFile(path string) string {
	b, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	return string(b)
}

func fail(format string, a ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", a...)
	os.Exit(1)
}
